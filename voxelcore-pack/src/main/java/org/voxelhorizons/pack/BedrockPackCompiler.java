package org.voxelhorizons.pack;

import com.google.gson.*;
import org.voxelhorizons.content.item.ItemDefinition;
import org.voxelhorizons.content.load.ContentLoader;
import org.voxelhorizons.content.pack.ContentPack;
import org.voxelhorizons.content.pack.ContentPackDiscovery;
import java.io.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.security.MessageDigest;
import java.util.*;
import java.util.stream.Stream;
import java.util.zip.*;

/** Bedrock resource pack and Geyser v2 mappings. Gameplay remains on the Java server. */
public final class BedrockPackCompiler {
    private static final Gson JSON = new GsonBuilder().setPrettyPrinting().create();

    public Result compile(Path contentRoot, Path outputRoot) throws IOException {
        Map<String, byte[]> assets = new TreeMap<String, byte[]>();
        List<ContentPack> packs = new ContentPackDiscovery().discover(contentRoot);
        for (ContentPack pack : packs) {
            Path root = pack.root().resolve("bedrock/resource_pack");
            if (!Files.exists(root)) continue;
            try (Stream<Path> paths = Files.walk(root)) {
                for (Path file : (Iterable<Path>) paths.sorted()::iterator) {
                    if (Files.isSymbolicLink(file)) throw new IOException("Bedrock assets cannot be symlinks: " + file);
                    if (!Files.isRegularFile(file)) continue;
                    String name = root.relativize(file).toString().replace('\\', '/');
                    if (name.equals("manifest.json") || name.equals("textures/item_texture.json"))
                        throw new IOException("Bedrock file is generated by VoxelCore: " + name);
                    put(assets, name, Files.readAllBytes(file));
                }
            }
        }
        JsonObject items = new JsonObject();
        JsonObject textures = new JsonObject();
        Set<String> selectors = new HashSet<String>();
        List<String> unsupported = new ArrayList<String>();
        Map<String, byte[]> javaAssets = new TreeMap<String, byte[]>();
        for (ContentPack pack : packs) {
            Path root = pack.root().resolve("assets");
            if (Files.exists(root)) try (Stream<Path> paths = Files.walk(root)) {
                for (Path file : (Iterable<Path>) paths.filter(Files::isRegularFile).sorted()::iterator)
                    put(javaAssets, "assets/" + root.relativize(file).toString().replace('\\', '/'), Files.readAllBytes(file));
            }
        }
        BedrockIconRenderer renderer = new BedrockIconRenderer(javaAssets);
        Map<String, byte[]> rendered = new HashMap<String, byte[]>();
        int count = 0;
        for (ItemDefinition item : new ContentLoader().load(contentRoot).entries().values()) {
            if (item.abstractDefinition() || item.render() == null || item.render().model() == null) continue;
            Object raw = item.properties().get("bedrock");
            byte[] png = null;
            if (raw == null) {
                try {
                    if (!item.render().rule().isEmpty()) throw new IOException("Conditional model requires explicit texture");
                    String modelKey = item.render().model();
                    png = rendered.get(modelKey);
                    if (png == null) {
                        MessageDigest cacheDigest;
                        try { cacheDigest = MessageDigest.getInstance("SHA-256"); } catch (Exception e) { throw new IllegalStateException(e); }
                        cacheDigest.update(("renderer-v1:" + modelKey).getBytes(StandardCharsets.UTF_8));
                        for (Map.Entry<String, byte[]> asset : javaAssets.entrySet()) {
                            cacheDigest.update(asset.getKey().getBytes(StandardCharsets.UTF_8));
                            cacheDigest.update((byte) 0); cacheDigest.update(asset.getValue());
                        }
                        Path cache = outputRoot.resolve("icon-cache").resolve(hex(cacheDigest.digest()) + ".png");
                        if (Files.isRegularFile(cache)) png = Files.readAllBytes(cache);
                        else {
                            png = renderer.render(modelKey); Files.createDirectories(cache.getParent());
                            Files.write(cache, png);
                        }
                        rendered.put(modelKey, png);
                    }
                } catch (IOException | RuntimeException failure) {
                    unsupported.add(item.id() + ": " + failure.getMessage()); continue;
                }
            } else {
            if (!(raw instanceof Map)) throw new IOException("properties.bedrock must be a map: " + item.id());
            Object texture = ((Map<?, ?>) raw).get("texture");
            if (!(texture instanceof String) || !((String) texture).matches("[a-z0-9_.-]+:[a-z0-9_./-]+")
                    || ((String) texture).contains(".."))
                throw new IOException("Expected namespaced PNG texture without extension for " + item.id());
            String[] key = ((String) texture).split(":", 2);
            for (ContentPack pack : packs) {
                Path file = pack.root().resolve("assets/" + key[0] + "/textures/" + key[1] + ".png");
                if (Files.isRegularFile(file)) {
                    byte[] next = Files.readAllBytes(file);
                    if (png != null && !Arrays.equals(png, next)) throw new IOException("Conflicting texture " + texture);
                    png = next;
                }
            }
            if (png == null) throw new IOException("Missing Bedrock item texture " + texture + " for " + item.id());
            }
            if (png.length < 8 || png[0] != (byte) 137 || png[1] != 80 || png[2] != 78 || png[3] != 71
                    || javax.imageio.ImageIO.read(new ByteArrayInputStream(png)) == null)
                throw new IOException("Not a PNG texture for " + item.id());
            String material = item.material().toLowerCase(Locale.ROOT);
            if (!material.contains(":")) material = "minecraft:" + material;
            String model = item.render().model();
            if (!selectors.add(material + "|" + model))
                throw new IOException("Ambiguous Bedrock mapping for " + material + " / " + model);
            // Hex-encoded ID preserves uniqueness even for slash/underscore combinations.
            String identifier = "voxelcore:i_" + hex(item.id().toString().getBytes(StandardCharsets.UTF_8));
            String icon = identifier.replace(':', '.');
            String path = "textures/voxelcore/" + identifier.substring(identifier.indexOf(':') + 1);
            put(assets, path + ".png", png);
            JsonObject tex = new JsonObject(); tex.addProperty("textures", path); textures.add(icon, tex);
            JsonObject definition = new JsonObject();
            definition.addProperty("type", "definition");
            definition.addProperty("model", model);
            definition.addProperty("bedrock_identifier", identifier);
            JsonObject options = new JsonObject(); options.addProperty("icon", icon);
            definition.add("bedrock_options", options);
            if (!items.has(material)) items.add(material, new JsonArray());
            items.getAsJsonArray(material).add(definition);
            count++;
        }
        if (count == 0 && assets.isEmpty()) throw new IOException("No Bedrock assets or mapped items; add properties.bedrock.texture or bedrock/resource_pack assets");
        JsonObject atlas = new JsonObject();
        atlas.addProperty("resource_pack_name", "VoxelCore"); atlas.addProperty("texture_name", "atlas.items");
        atlas.add("texture_data", textures); put(assets, "textures/item_texture.json", bytes(atlas));
        JsonObject mappings = new JsonObject(); mappings.addProperty("format_version", 2); mappings.add("items", items);
        byte[] mappingBytes = bytes(mappings);
        MessageDigest digest;
        try { digest = MessageDigest.getInstance("SHA-256"); } catch (Exception e) { throw new IllegalStateException(e); }
        for (Map.Entry<String, byte[]> entry : assets.entrySet()) {
            digest.update(entry.getKey().getBytes(StandardCharsets.UTF_8)); digest.update((byte) 0);
            digest.update(entry.getValue());
        }
        Collections.sort(unsupported);
        digest.update(unsupported.toString().getBytes(StandardCharsets.UTF_8));
        digest.update(mappingBytes);
        byte[] hash = digest.digest(); String revision = hex(hash);
        JsonArray version = new JsonArray();
        for (int i = 0; i < 3; i++) version.add(((hash[i * 2] & 255) << 8) | (hash[i * 2 + 1] & 255));
        JsonObject manifest = new JsonObject(); manifest.addProperty("format_version", 2);
        JsonObject header = new JsonObject(); header.addProperty("name", "VoxelCore");
        header.addProperty("description", "VoxelCore Bedrock resources " + revision.substring(0, 12));
        header.addProperty("uuid", UUID.nameUUIDFromBytes("VoxelCore:bedrock:header".getBytes(StandardCharsets.UTF_8)).toString());
        header.add("version", version); header.add("min_engine_version", JsonParser.parseString("[1,21,50]"));
        manifest.add("header", header);
        JsonObject module = new JsonObject(); module.addProperty("type", "resources");
        module.addProperty("uuid", UUID.nameUUIDFromBytes("VoxelCore:bedrock:resources".getBytes(StandardCharsets.UTF_8)).toString());
        module.add("version", version); JsonArray modules = new JsonArray(); modules.add(module); manifest.add("modules", modules);
        put(assets, "manifest.json", bytes(manifest));
        // Immutable revision directory is the publish unit; incomplete builds never become results.
        Files.createDirectories(outputRoot);
        Path staging = Files.createTempDirectory(outputRoot, ".bedrock-");
        try {
            try (ZipOutputStream zip = new ZipOutputStream(Files.newOutputStream(staging.resolve("voxelcore.mcpack")))) {
                for (Map.Entry<String, byte[]> entry : assets.entrySet()) {
                    ZipEntry ze = new ZipEntry(entry.getKey()); ze.setTime(0); zip.putNextEntry(ze);
                    zip.write(entry.getValue()); zip.closeEntry();
                }
            }
            Files.write(staging.resolve("voxelcore-items.json"), mappingBytes);
            Files.write(staging.resolve("unsupported-items.txt"), unsupported, StandardCharsets.UTF_8);
            Path destination = outputRoot.resolve(revision);
            if (!Files.exists(destination)) Files.move(staging, destination);
            return new Result(destination, count, unsupported.size(), revision);
        } finally {
            if (Files.exists(staging)) try (Stream<Path> paths = Files.walk(staging)) {
                for (Path path : (Iterable<Path>) paths.sorted(Comparator.reverseOrder())::iterator) Files.delete(path);
            }
        }
    }
    private static void put(Map<String, byte[]> assets, String name, byte[] value) throws IOException {
        byte[] previous = assets.put(name, value);
        if (previous != null && !Arrays.equals(previous, value)) throw new IOException("Bedrock asset collision: " + name);
    }
    private static byte[] bytes(JsonObject value) { return JSON.toJson(value).getBytes(StandardCharsets.UTF_8); }
    private static String hex(byte[] bytes) {
        StringBuilder out = new StringBuilder(); for (byte b : bytes) out.append(String.format(Locale.ROOT, "%02x", b & 255)); return out.toString();
    }
    public static final class Result {
        public final Path directory; public final int mappedItems; public final int unsupportedItems; public final String revision;
        Result(Path directory, int mappedItems, int unsupportedItems, String revision) {
            this.directory = directory; this.mappedItems = mappedItems; this.unsupportedItems = unsupportedItems; this.revision = revision;
        }
    }
}
